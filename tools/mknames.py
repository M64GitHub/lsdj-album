# Write song names (8 chars each, in slot order) from an LSDj .sav as RGBDS source.
# usage: mknames.py songs.sav out.asm
# SPDX-License-Identifier: GPL-2.0-or-later
import sys
d = open(sys.argv[1], "rb").read()
ok = set("ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789x ")
with open(sys.argv[2], "w") as f:
    f.write('; generated by tools/mknames.py\nINCLUDE "gfx_const.inc"\nSECTION "song_names", ROM0\nSongNames::\n')
    for i in range(32):
        raw = d[0x8000 + i*8 : 0x8008 + i*8]
        if raw[0] == 0:
            continue
        name = "".join(c if c in ok else " " for c in raw.split(b"\0")[0].decode("latin-1")).ljust(8)[:8]
        f.write(f'    db "{name}"   ; slot {i+1}\n')
    f.write("SongNamesEnd::\n")
